        closeDropdownSubPanel()
        if windowObj.Connections then
            for _, conn in ipairs(windowObj.Connections) do
                pcall(function()
                    if typeof(conn) == "RBXScriptConnection" then
                        conn:Disconnect()
                    elseif typeof(conn) == "table" and typeof(conn.Disconnect) == "function" then
                        conn:Disconnect()
                    end
                end)
            end
