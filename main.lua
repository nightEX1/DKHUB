                updateTriggerBtnText()
                if subPanel.Visible and windowObj.CurrentActiveDropdown and windowObj.CurrentActiveDropdown.UpdateTriggerBtn == updateTriggerBtnText then
                    renderSubPanelOptions()
                end
                fireChoiceChanged()
            end

